/* Applies page-specific Japanese copy after the Japanese DOM is ready. */
(function () {
  'use strict';
  function pageKey() {
    var path = window.location.pathname.replace(/^\/jp(?=\/|$)/, '');
    return path || '/beranda.html';
  }
  function dictionary() {
    return Object.assign({}, window.ICHIKARA_JP_COPY.shared || {}, window.ICHIKARA_JP_COPY[pageKey()] || {});
  }
  function translate(value, map) {
    if (typeof value !== 'string') return value;
    var direct = map[value];
    if (direct) return direct;
    var leading = value.match(/^\s*/)[0], trailing = value.match(/\s*$/)[0];
    var core = value.slice(leading.length, value.length - trailing.length);
    return map[core] ? leading + map[core] + trailing : value;
  }
  function apply(root) {
    var map = dictionary();
    var walker = document.createTreeWalker(root || document.body, NodeFilter.SHOW_TEXT, {
      acceptNode: function (node) {
        var parent = node.parentElement;
        return !parent || /^(SCRIPT|STYLE|NOSCRIPT|TEXTAREA)$/i.test(parent.tagName) ? NodeFilter.FILTER_REJECT : NodeFilter.FILTER_ACCEPT;
      }
    });
    var node;
    while ((node = walker.nextNode())) node.nodeValue = translate(node.nodeValue, map);
    (root || document).querySelectorAll('[placeholder],[title],[aria-label],[alt]').forEach(function (el) {
      ['placeholder', 'title', 'aria-label', 'alt'].forEach(function (attribute) {
        if (el.hasAttribute(attribute)) el.setAttribute(attribute, translate(el.getAttribute(attribute), map));
      });
    });
    document.title = translate(document.title, map);
    var description = document.querySelector('meta[name="description"]');
    if (description) description.setAttribute('content', translate(description.getAttribute('content'), map));
  }
  window.IchikaraJapanese = { apply: apply, translate: function (value) { return translate(value, dictionary()); }, story: function (story, field) {
    var japanese = story && (story[field + 'Ja'] || (story.ja && story.ja[field]));
    return japanese || (story && story[field]) || '';
  } };
  apply();
  var observer = new MutationObserver(function (mutations) {
    mutations.forEach(function (mutation) { mutation.addedNodes.forEach(function (node) { if (node.nodeType === Node.ELEMENT_NODE) apply(node); }); });
  });
  if (document.body) observer.observe(document.body, { childList: true, subtree: true });
}());

